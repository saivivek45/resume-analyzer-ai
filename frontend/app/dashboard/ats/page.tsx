"use client";

import { useState } from "react";
import { CheckSquare, Wand2, AlertTriangle } from "lucide-react";
import { Card } from "@/components/ui/card";
import { EmptyState } from "@/components/ui/empty-state";
import { FileUpload } from "@/components/ui/file-upload";
import { PageHeader } from "@/components/ui/page-header";
import { ProgressRing } from "@/components/ui/progress-ring";
import { useResumeUpload } from "@/components/dashboard/resume-upload-context";
import api from "@/src/lib/api";

type MatchResult = {
  match_score: number;
  missing_keywords: string[];
  suggestions: string[];
};

export default function AtsCheckerPage() {
  const upload = useResumeUpload();
  const [jobDescription, setJobDescription] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [matchResult, setMatchResult] = useState<MatchResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  const checkMatch = async () => {
    if (!jobDescription) {
      setError("Please paste a job description.");
      return;
    }
    
    setIsLoading(true);
    setError(null);
    try {
      const res = await api.post("/ats/match", {
        job_description: jobDescription
      });
      setMatchResult(res.data);
    } catch (err: any) {
      setError(err.response?.data?.detail || "Failed to check ATS match. Did you upload a resume first?");
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="ATS Checker"
        title="Keyword alignment"
        description="Paste a job description to see how well your resume matches using AI."
      />

      {error && (
        <div className="rounded-xl border border-red-500/20 bg-red-500/10 p-4 text-sm text-red-200 flex items-center gap-2">
          <AlertTriangle size={16} />
          {error}
        </div>
      )}

      <div className="grid gap-5 lg:grid-cols-[0.9fr_1.1fr]">
        <Card>
          <h2 className="text-lg font-semibold text-white">Resume Upload</h2>
          <div className="mt-5">
            <FileUpload
              selectedFile={upload.selectedFile}
              error={upload.uploadError}
              success={upload.uploadSuccess}
              isUploading={upload.isUploading}
              onClear={upload.clearFile}
              onSelect={upload.selectFile}
              onUpload={() => void upload.uploadResume()}
            />
          </div>
        </Card>
        <Card>
          <h2 className="text-lg font-semibold text-white">Job Description Input</h2>
          <textarea 
            className="form-input mt-4 min-h-64 resize-none" 
            placeholder="Paste the target job description"
            value={jobDescription}
            onChange={(e) => setJobDescription(e.target.value)}
          />
          <button 
            className="button-primary mt-4" 
            type="button" 
            onClick={checkMatch}
            disabled={isLoading || !jobDescription}
          >
            <Wand2 size={16} className={isLoading ? "animate-spin" : ""} />
            {isLoading ? "Analyzing Match..." : "Check ATS Match"}
          </button>
        </Card>
      </div>

      <div className="grid gap-5 lg:grid-cols-[18rem_1fr_1fr]">
        <Card>
          <ProgressRing label="Keyword Match %" value={matchResult?.match_score || 0} size="lg" />
        </Card>
        {matchResult ? (
          <Card>
            <h2 className="text-lg font-semibold text-white flex items-center gap-2"><CheckSquare size={18} className="text-cyan-300"/> Missing Keywords</h2>
            <ul className="mt-4 space-y-2">
              {matchResult.missing_keywords.map((kw, i) => (
                <li key={i} className="text-sm text-slate-400 bg-slate-800/50 p-2 rounded-md">• {kw}</li>
              ))}
            </ul>
          </Card>
        ) : (
          <EmptyState icon={CheckSquare} title="Missing Keywords" description="Keyword gaps will appear here after the ATS matching endpoint is connected." />
        )}
        
        {matchResult ? (
          <Card>
            <h2 className="text-lg font-semibold text-white flex items-center gap-2"><Wand2 size={18} className="text-purple-400"/> Suggestions</h2>
            <ul className="mt-4 space-y-2">
              {matchResult.suggestions.map((sug, i) => (
                <li key={i} className="text-sm text-slate-400 bg-slate-800/50 p-2 rounded-md">{sug}</li>
              ))}
            </ul>
          </Card>
        ) : (
          <EmptyState icon={Wand2} title="Suggestions" description="Suggestions will be generated by future backend responses." />
        )}
      </div>
    </div>
  );
}
